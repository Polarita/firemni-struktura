-- =====================================================================================
-- rls-pool-test.sql — Polarita Elektro Cloud · Blok 19 (S7) · Verze 3.7 (Polarita-3.7)
--
-- EN: Tested on disposable PostgreSQL 18.7. Companion of rls-vzor.sql. That file runs in one
--     transaction and switches roles with SET LOCAL ROLE; this script covers what it
--     cannot: a REAL login of saas_app and a connection that is reused for further
--     transactions after COMMIT and after ROLLBACK, as a connection pool does.
-- CZ: Ověřeno na dočasné instanci PostgreSQL 18.7. Doplněk k rls-vzor.sql. Ten běží v jedné transakci
--     a role přepíná přes SET LOCAL ROLE; tento skript pokrývá to, co on nemůže:
--     SKUTEČNÉ přihlášení role saas_app a spojení, které se po COMMIT i po ROLLBACK
--     použije pro další transakce, jak to dělá pool spojení.
--
-- EN: Requirements — read before running:
--     (1) psql only: the script uses psql meta-commands (\connect, \gset, \if). It cannot
--         be run through another client or as one SQL string.
--     (2) It needs SEPARATE CONNECTIONS: it opens a connection as the administrator, then
--         logs in as saas_app (twice), then returns to the administrator. The throw-away
--         instance must therefore let saas_app log in to this database (host-based
--         authentication of the instance; the password is supplied outside this file,
--         for example by the password file of the client). No password is written here:
--         pass it as the psql variable heslo_app.
--     (3) EMPTY throw-away database on a throw-away instance, administrator = superuser.
--         Unlike rls-vzor.sql this script COMMITS: roles are cluster-wide objects, so it
--         must never be run on an instance where a role saas_app already exists. Part D
--         drops everything again; if the script stops earlier, run part D by hand.
--     (4) The fixture is a REDUCED copy of rls-vzor.sql (registry, session tokens, one
--         business table, the resolver by token and expiry). Tenant state, session
--         generation and the other roles are proven in rls-vzor.sql; in the real release
--         pipeline both tests run against the schema generated by metadata-schema-kernel,
--         not against a hand-made copy.
--     (5) It does not replace a test through the real pooler: the reset behaviour of the
--         deployed pooler must be verified against its official documentation and tested
--         through it when Block 19 is built. Because of (4) a pass says nothing about the
--         isolation of the REAL schema either.
--     (6) Running and result: psql -X -v heslo_app="$HESLO_APP" -f rls-pool-test.sql
--         (the script sets ON_ERROR_STOP itself). A missing or empty heslo_app and every
--         failed check end with a non-zero exit code. The run PASSED only when the exit
--         code is 0 AND the last line of the standard output is exactly
--         RLS_POOL_TEST_RESULT=PASS - the caller must check both.
-- CZ: Požadavky — přečti před spuštěním:
--     (1) Pouze psql: skript používá meta-příkazy psql (\connect, \gset, \if). Nelze jej
--         spustit jiným klientem ani jako jeden řetězec SQL.
--     (2) Vyžaduje SAMOSTATNÁ SPOJENÍ: otevře spojení jako administrátor, poté se přihlásí
--         jako saas_app (dvakrát) a nakonec se vrátí k administrátorovi. Instance určená
--         k zahození proto musí roli saas_app dovolit přihlášení k této databázi (pravidla
--         ověřování klientů dané instance; heslo se dodává mimo tento soubor, například
--         souborem hesel klienta). Žádné heslo zde zapsáno není: předej je jako proměnnou
--         psql heslo_app.
--     (3) PRÁZDNÁ databáze určená k zahození na instanci určené k zahození, administrátor
--         = superuser. Na rozdíl od rls-vzor.sql tento skript POTVRZUJE (COMMIT): role
--         jsou objekty celého klastru, proto se nesmí spustit na instanci, kde už role
--         saas_app existuje. Část D vše opět odstraní; zastaví-li se skript dřív, spusť
--         část D ručně.
--     (4) Přípravek je ZMENŠENÁ kopie rls-vzor.sql (registr, tokeny relací, jedna doménová
--         tabulka, resolver podle tokenu a expirace). Stav tenanta, generaci relací
--         a ostatní role dokládá rls-vzor.sql; ve skutečném vydávacím řetězci běží oba
--         testy proti schématu vygenerovanému modulem metadata-schema-kernel, ne proti
--         ruční kopii.
--     (5) Nenahrazuje test přes skutečný pooler: chování nasazeného pooleru při vracení
--         spojení je nutné ověřit proti jeho oficiální dokumentaci a otestovat přes něj
--         při stavbě Bloku 19. Kvůli bodu (4) průchod nevypovídá ani o izolaci SKUTEČNÉHO
--         schématu.
--     (6) Spuštění a výsledek: psql -X -v heslo_app="$HESLO_APP" -f rls-pool-test.sql
--         (ON_ERROR_STOP si skript nastavuje sám). Chybějící nebo prázdné heslo_app i každá
--         neprošlá kontrola končí nenulovým návratovým kódem. Běh PROŠEL jen tehdy, když je
--         návratový kód 0 A ZÁROVEŇ poslední řádek standardního výstupu je přesně
--         RLS_POOL_TEST_RESULT=PASS - volající musí ověřit obojí.
-- =====================================================================================

\set ON_ERROR_STOP on

-- EN: The mandatory input heslo_app. A missing or empty value must end as a REAL ERROR
--     (non-zero exit code of psql under ON_ERROR_STOP), never as a quiet \quit with code 0:
--     a job that ran no check must not look green. The administrator connection is already
--     open here, so the failure is raised by the server.
-- CZ: Povinný vstup heslo_app. Chybějící nebo prázdná hodnota musí skončit SKUTEČNOU CHYBOU
--     (nenulový návratový kód psql při ON_ERROR_STOP), nikdy tichým \quit s kódem 0: úloha,
--     která neprovedla žádnou kontrolu, nesmí vypadat zeleně. Spojení administrátora je zde
--     už otevřené, chybu proto vyvolá server.
\if :{?heslo_app}
    SELECT btrim(:'heslo_app') = '' AS heslo_app_prazdne \gset
\else
    \set heslo_app_prazdne true
\endif
\if :heslo_app_prazdne
    \echo 'STOP: psql variable heslo_app is missing or empty / proměnná psql heslo_app chybí nebo je prázdná'
    DO $$ BEGIN RAISE EXCEPTION 'rls-pool-test.sql STOP: psql variable heslo_app is missing or empty - no check was run'; END $$;
\endif

-- -------------------------------------------------------------------------------------
-- A. Fixture, committed by the administrator / Přípravek, potvrzený administrátorem
-- -------------------------------------------------------------------------------------
SELECT current_user AS spravce \gset

BEGIN;

CREATE ROLE saas_app LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT
    PASSWORD :'heslo_app';

-- EN: Same PROPOSED limits as in rls-vzor.sql; they apply at login, which part B checks.
-- CZ: Stejné NAVRŽENÉ limity jako v rls-vzor.sql; platí od přihlášení, což ověřuje část B.
ALTER ROLE saas_app SET statement_timeout = '30s';
ALTER ROLE saas_app SET idle_in_transaction_session_timeout = '60s';

CREATE SCHEMA saas_vzor;
REVOKE ALL ON SCHEMA saas_vzor FROM PUBLIC;

CREATE TABLE saas_vzor.tenant (
    tenant_id uuid PRIMARY KEY,
    nazev     text NOT NULL
);

CREATE TABLE saas_vzor.tenant_session (
    token      uuid PRIMARY KEY,
    tenant_id  uuid NOT NULL REFERENCES saas_vzor.tenant (tenant_id),
    expires_at timestamptz NOT NULL
);

CREATE FUNCTION saas_vzor.current_tenant_id()
RETURNS uuid
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    raw_token text;
    v_token   uuid;
    v_tenant  uuid;
BEGIN
    raw_token := NULLIF(current_setting('app.tenant_token', true), '');
    IF raw_token IS NULL THEN
        RETURN NULL;
    END IF;
    BEGIN
        v_token := raw_token::uuid;
    EXCEPTION
        WHEN invalid_text_representation THEN
            RETURN NULL;
    END;
    SELECT s.tenant_id
      INTO v_tenant
      FROM saas_vzor.tenant_session AS s
     WHERE s.token = v_token
       AND s.expires_at > statement_timestamp();
    RETURN v_tenant;
END;
$$;
REVOKE ALL ON FUNCTION saas_vzor.current_tenant_id() FROM PUBLIC;

CREATE TABLE saas_vzor.objekt (
    objekt_id uuid NOT NULL DEFAULT gen_random_uuid(),
    tenant_id uuid NOT NULL
              DEFAULT saas_vzor.current_tenant_id()
              REFERENCES saas_vzor.tenant (tenant_id),
    nazev     text NOT NULL,
    PRIMARY KEY (tenant_id, objekt_id)
);

ALTER TABLE saas_vzor.tenant         ENABLE ROW LEVEL SECURITY;
ALTER TABLE saas_vzor.tenant         FORCE  ROW LEVEL SECURITY;
ALTER TABLE saas_vzor.tenant_session ENABLE ROW LEVEL SECURITY;
ALTER TABLE saas_vzor.tenant_session FORCE  ROW LEVEL SECURITY;
ALTER TABLE saas_vzor.objekt         ENABLE ROW LEVEL SECURITY;
ALTER TABLE saas_vzor.objekt         FORCE  ROW LEVEL SECURITY;

CREATE POLICY tenant_guard ON saas_vzor.objekt
    AS RESTRICTIVE
    FOR ALL
    TO PUBLIC
    USING      (tenant_id = (SELECT saas_vzor.current_tenant_id()))
    WITH CHECK (tenant_id = (SELECT saas_vzor.current_tenant_id()));

CREATE POLICY objekt_app_access ON saas_vzor.objekt
    AS PERMISSIVE
    FOR ALL
    TO saas_app
    USING      (true)
    WITH CHECK (true);

GRANT USAGE ON SCHEMA saas_vzor TO saas_app;
GRANT EXECUTE ON FUNCTION saas_vzor.current_tenant_id() TO saas_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON saas_vzor.objekt TO saas_app;

-- EN: Synthetic data are written by the administrator (a superuser bypasses RLS; this is
--     acceptable ONLY for this fixture — rls-vzor.sql seeds through the policies).
-- CZ: Syntetická data zapisuje administrátor (superuser RLS obchází; to je přípustné JEN
--     pro tento přípravek — rls-vzor.sql plní data přes politiky).
INSERT INTO saas_vzor.tenant (tenant_id, nazev) VALUES
    ('11111111-1111-4111-8111-111111111111', 'Vzorová elektro firma A (syntetická)'),
    ('22222222-2222-4222-8222-222222222222', 'Vzorová elektro firma B (syntetická)');
INSERT INTO saas_vzor.tenant_session (token, tenant_id, expires_at) VALUES
    ('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', '11111111-1111-4111-8111-111111111111',
     clock_timestamp() + interval '15 minutes'),
    ('bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb', '22222222-2222-4222-8222-222222222222',
     clock_timestamp() + interval '15 minutes');
INSERT INTO saas_vzor.objekt (tenant_id, nazev) VALUES
    ('11111111-1111-4111-8111-111111111111', 'Bytový dům Vzorová 1 (tenant A)'),
    ('11111111-1111-4111-8111-111111111111', 'Výrobní hala Vzorová 2 (tenant A)'),
    ('22222222-2222-4222-8222-222222222222', 'Bytový dům Příkladná 3 (tenant B)');

COMMIT;

-- -------------------------------------------------------------------------------------
-- B. Real login of saas_app; one connection reused for several transactions
--    Skutečné přihlášení saas_app; jedno spojení použité pro několik transakcí
-- -------------------------------------------------------------------------------------
\connect - saas_app

-- EN: POOL 1 — the login is real: session_user is saas_app, it is not a superuser, has no
--     BYPASSRLS, and the role-level limits were applied by the login itself.
-- CZ: POOL 1 — přihlášení je skutečné: session_user je saas_app, není superuser, nemá
--     BYPASSRLS a limity nastavené na roli se uplatnily samotným přihlášením.
DO $$
DECLARE
    n bigint;
BEGIN
    IF session_user <> 'saas_app' OR current_user <> 'saas_app' THEN
        RAISE EXCEPTION 'POOL 1 FAIL: connected as % / %', session_user, current_user;
    END IF;
    SELECT count(*) INTO n FROM pg_roles
     WHERE rolname = 'saas_app' AND (rolsuper OR rolbypassrls);
    IF n <> 0 THEN
        RAISE EXCEPTION 'POOL 1 FAIL: saas_app is superuser or has BYPASSRLS';
    END IF;
    IF current_setting('statement_timeout') IN ('0', '0ms')
       OR current_setting('idle_in_transaction_session_timeout') IN ('0', '0ms') THEN
        RAISE EXCEPTION 'POOL 1 FAIL: role-level time limits were not applied at login';
    END IF;
    SELECT count(*) INTO n FROM saas_vzor.objekt;
    IF n <> 0 THEN
        RAISE EXCEPTION 'POOL 1 FAIL: % rows visible right after login without a token', n;
    END IF;
    RAISE NOTICE 'POOL 1 PASS: real login, limits applied, 0 rows without a token';
END
$$;

-- EN: POOL 2 — request of tenant A ends with COMMIT. The token was set with
--     set_config(..., true), so it must be gone in the next transaction on the SAME
--     connection.
-- CZ: POOL 2 — požadavek tenanta A končí COMMIT. Token byl nastaven přes
--     set_config(..., true), takže v další transakci na TÉMŽE spojení už nesmí existovat.
BEGIN;
SELECT set_config('app.tenant_token', 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', true);
DO $$
DECLARE
    n bigint;
BEGIN
    SELECT count(*) INTO n FROM saas_vzor.objekt;
    IF n <> 2 THEN
        RAISE EXCEPTION 'POOL 2 FAIL: tenant A sees % rows instead of 2 inside its transaction', n;
    END IF;
END
$$;
COMMIT;

DO $$
DECLARE
    n bigint;
BEGIN
    IF NULLIF(current_setting('app.tenant_token', true), '') IS NOT NULL THEN
        RAISE EXCEPTION 'POOL 2 FAIL: token survived COMMIT on the reused connection';
    END IF;
    SELECT count(*) INTO n FROM saas_vzor.objekt;
    IF n <> 0 THEN
        RAISE EXCEPTION 'POOL 2 FAIL: % rows visible after COMMIT without a new token', n;
    END IF;
    RAISE NOTICE 'POOL 2 PASS: context gone after COMMIT / kontext po COMMIT zmizel';
END
$$;

-- EN: POOL 3 — request of tenant A ends with ROLLBACK (error path of the application).
-- CZ: POOL 3 — požadavek tenanta A končí ROLLBACK (chybová cesta aplikace).
BEGIN;
SELECT set_config('app.tenant_token', 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', true);
INSERT INTO saas_vzor.objekt (nazev) VALUES ('objekt z vrácené transakce');
ROLLBACK;

DO $$
DECLARE
    n bigint;
BEGIN
    IF NULLIF(current_setting('app.tenant_token', true), '') IS NOT NULL THEN
        RAISE EXCEPTION 'POOL 3 FAIL: token survived ROLLBACK on the reused connection';
    END IF;
    SELECT count(*) INTO n FROM saas_vzor.objekt;
    IF n <> 0 THEN
        RAISE EXCEPTION 'POOL 3 FAIL: % rows visible after ROLLBACK without a new token', n;
    END IF;
    RAISE NOTICE 'POOL 3 PASS: context gone after ROLLBACK / kontext po ROLLBACK zmizel';
END
$$;

-- EN: POOL 4 — the next client on the same connection is tenant B: it sees exactly its
--     own row, nothing of tenant A and nothing from the rolled-back transaction.
-- CZ: POOL 4 — dalším klientem na témže spojení je tenant B: vidí právě svůj řádek, nic
--     z tenanta A a nic z vrácené transakce.
BEGIN;
SELECT set_config('app.tenant_token', 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb', true);
DO $$
DECLARE
    n_all     bigint;
    n_foreign bigint;
BEGIN
    SELECT count(*),
           count(*) FILTER (WHERE tenant_id <> '22222222-2222-4222-8222-222222222222'::uuid)
      INTO n_all, n_foreign
      FROM saas_vzor.objekt;
    IF n_all <> 1 OR n_foreign <> 0 THEN
        RAISE EXCEPTION 'POOL 4 FAIL: tenant B sees % rows, % foreign on the reused connection', n_all, n_foreign;
    END IF;
    RAISE NOTICE 'POOL 4 PASS: next tenant on the same connection sees only its own row';
END
$$;
COMMIT;

-- EN: POOL 5 — why the token must NEVER be set for the whole session. A session-level
--     set_config(..., false) survives COMMIT: the following transaction on the same
--     connection would act as tenant A without presenting anything. The test proves the
--     leak exists, and that RESET ALL (part of what DISCARD ALL does) removes it. The
--     application therefore uses only the transaction-level form, and the pooler must
--     reset connections it hands over — verify against the official documentation of the
--     deployed pooler when Block 19 is built.
-- CZ: POOL 5 — proč se token NIKDY nesmí nastavit na celou relaci. Nastavení na úrovni
--     relace set_config(..., false) přežije COMMIT: následující transakce na témže spojení
--     by jednala jako tenant A, aniž by cokoli předložila. Test dokazuje, že únik
--     existuje a že jej RESET ALL (část toho, co dělá DISCARD ALL) odstraní. Aplikace
--     proto používá jen transakční tvar a pooler musí předávaná spojení resetovat —
--     ověřit proti oficiální dokumentaci nasazeného pooleru při stavbě Bloku 19.
BEGIN;
SELECT set_config('app.tenant_token', 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', false);
COMMIT;

DO $$
DECLARE
    n bigint;
BEGIN
    SELECT count(*) INTO n FROM saas_vzor.objekt;
    IF n <> 2 THEN
        RAISE EXCEPTION 'POOL 5 FAIL: expected the session-level token to leak (2 rows), saw %', n;
    END IF;
END
$$;

RESET ALL;

DO $$
DECLARE
    n bigint;
BEGIN
    SELECT count(*) INTO n FROM saas_vzor.objekt;
    IF n <> 0 THEN
        RAISE EXCEPTION 'POOL 5 FAIL: % rows visible after RESET ALL', n;
    END IF;
    RAISE NOTICE 'POOL 5 PASS: session-level token leaks across transactions, RESET ALL removes it';
END
$$;

-- -------------------------------------------------------------------------------------
-- C. A second, fresh login of saas_app / Druhé, nové přihlášení saas_app
-- -------------------------------------------------------------------------------------
\connect - saas_app

-- EN: POOL 6 — a new connection starts without any tenant context.
-- CZ: POOL 6 — nové spojení začíná bez jakéhokoli kontextu tenanta.
DO $$
DECLARE
    n bigint;
BEGIN
    SELECT count(*) INTO n FROM saas_vzor.objekt;
    IF n <> 0 THEN
        RAISE EXCEPTION 'POOL 6 FAIL: % rows visible on a fresh connection', n;
    END IF;
    RAISE NOTICE 'POOL 6 PASS: fresh connection has no tenant context';
END
$$;

-- -------------------------------------------------------------------------------------
-- D. Clean-up by the administrator / Úklid administrátorem
-- -------------------------------------------------------------------------------------
\connect - :spravce

DROP SCHEMA saas_vzor CASCADE;
DROP ROLE saas_app;

\echo 'rls-pool-test.sql: all POOL checks passed, fixture removed / všechny kontroly POOL prošly, přípravek odstraněn'

-- EN: RESULT LINE — the very last output of the script and the ONLY proof of a pass. It is
--     reached only when no statement and no \connect failed (ON_ERROR_STOP), POOL 1-6 ran
--     and part D removed the fixture. The caller (CI) accepts the run only when psql
--     returned 0 AND the last line of the standard output is exactly this line.
-- CZ: VÝSLEDKOVÝ ŘÁDEK — úplně poslední výstup skriptu a JEDINÝ doklad průchodu. Dosáhne se
--     jen tehdy, když neselhal žádný příkaz ani \connect (ON_ERROR_STOP), proběhly POOL 1-6
--     a část D odstranila přípravek. Volající (CI) běh přijme jen tehdy, když psql vrátil 0
--     A ZÁROVEŇ poslední řádek standardního výstupu je přesně tento řádek.
\echo 'RLS_POOL_TEST_RESULT=PASS'
